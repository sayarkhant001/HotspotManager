package com.example.utils

import com.example.domain.models.UserProfile
import org.json.JSONObject

/**
 * Builds the captive portal's LIVE data file (plans.js) 100% app-side —
 * no VPS involved. Contains the router's real SSID (brand) and the ACTUAL
 * price plans from the synced profile list. The portal's login.html loads
 * plans.js, re-brands itself, and renders Hot Plans cards using the theme's
 * own CSS variables, so every theme looks native automatically.
 */
object PortalDataHelper {

    fun humanData(mb: Int): String = when {
        mb <= 0 -> "Unlimited"
        mb >= 1024 && mb % 1024 == 0 -> "${mb / 1024} GB"
        mb >= 1024 -> String.format(java.util.Locale.US, "%.1f GB", mb / 1024.0)
        else -> "$mb MB"
    }

    fun humanValidity(durationMinutes: Int, validityDays: Int): String = when {
        durationMinutes > 0 -> {
            val h = durationMinutes / 60
            val m = durationMinutes % 60
            when {
                h > 0 && m > 0 -> "${h}h ${m}m"
                h > 0 -> "${h}h"
                else -> "${m}m"
            }
        }
        validityDays > 0 -> "$validityDays Day(s)"
        else -> "Unlimited"
    }

    fun humanPrice(price: Double): String =
        String.format(java.util.Locale.US, "%,d Ks", price.toLong())

    fun buildPlansJs(ssid: String, profiles: List<UserProfile>): String {
        val brand = ssid.trim().replace("\"", "").ifBlank { "WiFi Hotspot" }
        val escBrand = brand.replace("\\", "\\\\").replace("</", "<\\/")
        val plansArr = StringBuilder()
        profiles.filter { it.name.isNotBlank() }.forEachIndexed { i, p ->
            if (i > 0) plansArr.append(",")
            plansArr.append(JSONObject().apply {
                put("name", p.name)
                put("data", humanData(p.dataLimitMb))
                put("validity", humanValidity(p.durationMinutes, p.validityDays))
                put("speed", p.rateLimit.ifBlank { "" })
                put("price", humanPrice(p.price))
            }.toString())
        }
        return """/* Generated by HotspotManager - live portal data (brand + Hot Plans) */
window.PORTAL_BRAND = "$escBrand";
window.PORTAL_PLANS = [$plansArr];
(function() {
  var b = window.PORTAL_BRAND;
  if (b) {
    var els = document.querySelectorAll('#portal-brand, .brand-name');
    for (var i = 0; i < els.length; i++) { els[i].textContent = b; }
    try { document.title = b + ' - WiFi Login'; } catch (e) {}
  }
  var host = document.getElementById('hot-plans');
  if (host && window.PORTAL_PLANS.length) {
    var h = '';
    for (var j = 0; j < window.PORTAL_PLANS.length; j++) {
      var p = window.PORTAL_PLANS[j];
      h += '<div class="plan-card"><div class="plan-name">' + p.name + '</div>'
        + '<div class="plan-data">' + p.data + '</div>'
        + '<div class="plan-val">' + p.validity + (p.speed ? ' &bull; ' + p.speed : '') + '</div>'
        + '<div class="plan-price">' + p.price + '</div></div>';
    }
    host.innerHTML = h;
    var wrap = document.getElementById('hot-plans-wrap');
    if (wrap) wrap.style.display = 'block';
  }
})();"""
    }
}